#!/bin/sh
# Fill ../pythondata-cpu-rd68041 from Inputs/RD68041: the RTL LiteX builds the core
# from, as a standard LiteX pythondata package (get_data_mod("cpu", "rd68041")).
# RD68041 is an MC68040, or an MC68LC040 with its FPU parameter at 0; the FPU is part
# of the same RTL, so there is no second core here (sync_pythondata.sh does RD68031
# and RD68884).
#
# The RTL is copied as it is in the RD68041 commit checked out under Inputs/, keeping
# its rtl/ and rtl/gen/ layout (rtl/rd68041.vlt's waivers match on "*rtl/<file>").
# The file list, in compile order, is the one RD68041's Makefile builds from
# (make print-rtl, which only echoes it).
#
# Usage: scripts/sync_pythondata_rd68041.sh [destination]
set -eu

HERE=$(cd "$(dirname "$0")/.." && pwd)
SRC=$HERE/Inputs/RD68041
DST=${1:-$HERE/../pythondata-cpu-rd68041}
PKG=pythondata_cpu_rd68041

if [ -n "$(git -C "$SRC" status --porcelain --untracked-files=no)" ]; then
    echo "Inputs/RD68041 has local changes; refusing to snapshot it" >&2
    exit 1
fi
HASH=$(git -C "$SRC" rev-parse HEAD)
DESCRIBE=$(git -C "$SRC" describe --always --tags)
MSG=$(git -C "$SRC" log -1 --format='commit %H%nAuthor: %an <%ae>%nDate:   %ad%n%n    %s')

SOURCES=$(make -s -C "$SRC" --no-print-directory print-rtl | tr ' ' '\n' | sed '/^$/d')

# Every .sv in rtl/ must be in the list, so a module RD68041 adds is not lost.
for f in $(cd "$SRC" && ls rtl/*.sv rtl/gen/*.sv); do
    echo "$SOURCES" | grep -qx "$f" || { echo "$f is not in the file list" >&2; exit 1; }
done

mkdir -p "$DST"
DST=$(cd "$DST" && pwd)
rm -rf "$DST/$PKG/verilog"
mkdir -p "$DST/$PKG/verilog/rtl/gen"
for f in $SOURCES rtl/rd68041.vlt; do
    cp "$SRC/$f" "$DST/$PKG/verilog/$f"
done
echo "$SOURCES" > "$DST/$PKG/verilog/rd68041.f"
cp "$SRC/LICENSE" "$DST/LICENSE"

cat > "$DST/$PKG/__init__.py" <<EOF
# Generated by litex-68k/scripts/sync_pythondata_rd68041.sh -- do not edit.
import os.path
__dir__ = os.path.split(os.path.abspath(os.path.realpath(__file__)))[0]
data_location = os.path.join(__dir__, "verilog")
src = "https://github.com/MelkhiorVintageComputing/RD68041"

# Module version
version_str = "0.0"
version_tuple = (0, 0)

# Data version info: the RD68041 commit the RTL was copied from.
data_git_hash = "$HASH"
data_git_describe = "$DESCRIBE"
data_git_msg = """\\
$MSG
"""

# The RTL, relative to data_location, in compile order (packages first). The top
# is rd68041_top; its parameter FPU is 1 for the MC68040, 0 for the MC68LC040.
sources = [
$(echo "$SOURCES" | sed 's/.*/    "&",/')
]

# Verilator waivers, relative to data_location.
verilator_config = "rtl/rd68041.vlt"


def data_file(f):
    """Get absolute path for file inside $PKG."""
    fn = os.path.join(data_location, f)
    fn = os.path.abspath(fn)
    if not os.path.exists(fn):
        raise IOError("File {} doesn't exist in $PKG".format(f))
    return fn
EOF

cat > "$DST/pyproject.toml" <<EOF
[build-system]
requires = ["setuptools>=61", "wheel"]
build-backend = "setuptools.build_meta"

[project]
name = "pythondata-cpu-rd68041"
version = "0.0"
description = "Python module containing the SystemVerilog files of the RD68041 (MC68040 / MC68LC040) CPU"
license = {text = "CERN-OHL-S-2.0"}

[tool.setuptools.packages.find]
include = ["$PKG"]

[tool.setuptools.package-data]
$PKG = ["verilog/**/*"]
EOF

cat > "$DST/README.md" <<EOF
# pythondata-cpu-rd68041

The SystemVerilog of [RD68041](https://github.com/MelkhiorVintageComputing/RD68041),
an MC68040 (\`FPU = 1\`) or MC68LC040 (\`FPU = 0\`), packaged for LiteX
(\`get_data_mod("cpu", "rd68041")\`).

Generated by \`litex-68k/scripts/sync_pythondata_rd68041.sh\` from RD68041 commit
\`$HASH\` (\`$DESCRIBE\`). Do not edit; regenerate.

- \`$PKG/verilog/rtl/\`: the RTL, as in RD68041's \`rtl/\`.
- \`$PKG/verilog/rd68041.f\` and \`$PKG.sources\`: the files in compile order.
- \`$PKG/verilog/rtl/rd68041.vlt\`: RD68041's Verilator waivers.

The RTL is licensed under the CERN Open Hardware Licence Version 2 -- Strongly
Reciprocal (\`LICENSE\`).
EOF

printf '__pycache__/\n*.egg-info/\nbuild/\n' > "$DST/.gitignore"

echo "$DST: RD68041 $DESCRIBE ($HASH)"
