#!/bin/sh
# Fill ../pythondata-cpu-rd68031 from Inputs/RD68031: the RTL LiteX builds the core
# from, as a standard LiteX pythondata package (get_data_mod("cpu", "rd68031")).
#
# The RTL is copied as it is in the RD68031 commit checked out under Inputs/, keeping
# its rtl/ and rtl/gen/ layout (rtl/rd68031.vlt's waivers match on "*rtl/<file>").
# The package records that commit and the dependency-ordered file list of RD68031's
# Makefile (packages first).
#
# Usage: scripts/sync_pythondata.sh [destination]
set -eu

HERE=$(cd "$(dirname "$0")/.." && pwd)
SRC=$HERE/Inputs/RD68031
DST=${1:-$HERE/../pythondata-cpu-rd68031}
PKG=pythondata_cpu_rd68031

if [ -n "$(git -C "$SRC" status --porcelain --untracked-files=no)" ]; then
    echo "Inputs/RD68031 has local changes; refusing to snapshot it" >&2
    exit 1
fi
HASH=$(git -C "$SRC" rev-parse HEAD)
DESCRIBE=$(git -C "$SRC" describe --always --tags)
MSG=$(git -C "$SRC" log -1 --format='commit %H%nAuthor: %an <%ae>%nDate:   %ad%n%n    %s')

# The order of RD68031's Makefile (RTL := PKGS GENPKG GENSRC SRCS).
SOURCES="rtl/rd68031_pkg.sv
$(cd "$SRC" && ls rtl/gen/*_pkg.sv)
$(cd "$SRC" && ls rtl/gen/*.sv | grep -v '_pkg\.sv$')
rtl/rd68031_sync.sv
rtl/rd68031_dedge_ff.sv
rtl/rd68031_shifter.sv
rtl/rd68031_divider.sv
rtl/rd68031_bitfield.sv
rtl/rd68031_biu.sv
rtl/rd68031_icache.sv
rtl/rd68031_dcache.sv
rtl/rd68031_ifu.sv
rtl/rd68031_mmu_xl.sv
rtl/rd68031_mmu.sv
rtl/rd68031_seq.sv
rtl/rd68031_top.sv"

# Every .sv in rtl/ must be in the list, so a module RD68031 adds is not lost.
for f in $(cd "$SRC" && ls rtl/*.sv rtl/gen/*.sv); do
    echo "$SOURCES" | grep -qx "$f" || { echo "$f is not in the file list" >&2; exit 1; }
done

mkdir -p "$DST"
DST=$(cd "$DST" && pwd)
rm -rf "$DST/$PKG/verilog"
mkdir -p "$DST/$PKG/verilog/rtl/gen"
for f in $SOURCES rtl/rd68031.vlt; do
    cp "$SRC/$f" "$DST/$PKG/verilog/$f"
done
echo "$SOURCES" > "$DST/$PKG/verilog/rd68031.f"
cp "$SRC/LICENSE" "$DST/LICENSE"

cat > "$DST/$PKG/__init__.py" <<EOF
# Generated by litex-68k/scripts/sync_pythondata.sh -- do not edit.
import os.path
__dir__ = os.path.split(os.path.abspath(os.path.realpath(__file__)))[0]
data_location = os.path.join(__dir__, "verilog")
src = "https://github.com/MelkhiorVintageComputing/RD68031"

# Module version
version_str = "0.0"
version_tuple = (0, 0)

# Data version info: the RD68031 commit the RTL was copied from.
data_git_hash = "$HASH"
data_git_describe = "$DESCRIBE"
data_git_msg = """\\
$MSG
"""

# The RTL, relative to data_location, in compile order (packages first).
sources = [
$(echo "$SOURCES" | sed 's/.*/    "&",/')
]

# Verilator waivers, relative to data_location.
verilator_config = "rtl/rd68031.vlt"


def data_file(f):
    """Get absolute path for file inside $PKG."""
    fn = os.path.join(data_location, f)
    fn = os.path.abspath(fn)
    if not os.path.exists(fn):
        raise IOError("File {} doesn't exist in $PKG".format(f))
    return fn
EOF

cat > "$DST/pyproject.toml" <<EOF
[build-system]
requires = ["setuptools>=61", "wheel"]
build-backend = "setuptools.build_meta"

[project]
name = "pythondata-cpu-rd68031"
version = "0.0"
description = "Python module containing the SystemVerilog files of the RD68031 (MC68030) CPU"
license = {text = "CERN-OHL-S-2.0"}

[tool.setuptools.packages.find]
include = ["$PKG"]

[tool.setuptools.package-data]
$PKG = ["verilog/**/*"]
EOF

cat > "$DST/README.md" <<EOF
# pythondata-cpu-rd68031

The SystemVerilog of [RD68031](https://github.com/MelkhiorVintageComputing/RD68031),
an MC68030, packaged for LiteX (\`get_data_mod("cpu", "rd68031")\`).

Generated by \`litex-68k/scripts/sync_pythondata.sh\` from RD68031 commit
\`$HASH\` (\`$DESCRIBE\`). Do not edit; regenerate.

- \`$PKG/verilog/rtl/\`: the RTL, as in RD68031's \`rtl/\`.
- \`$PKG/verilog/rd68031.f\` and \`$PKG.sources\`: the files in compile order.
- \`$PKG/verilog/rtl/rd68031.vlt\`: RD68031's Verilator waivers.

The RTL is licensed under the CERN Open Hardware Licence Version 2 -- Strongly
Reciprocal (\`LICENSE\`).
EOF

printf '__pycache__/\n*.egg-info/\nbuild/\n' > "$DST/.gitignore"

echo "$DST: RD68031 $DESCRIBE ($HASH)"
