# Regenerate linux.defconfig, the kernel configuration buildroot uses
# (doc/l8-buildroot.md): allnoconfig with L7's linux/litex-rd68031.config and
# linux-buildroot.config, saved with savedefconfig. Buildroot expands it with
# olddefconfig, which gives back that same configuration: what savedefconfig
# leaves out is at its default, and allnoconfig's departures from the defaults
# are written as "is not set".
#
#   buildroot/board/litex-rd68031/make-linux-defconfig.sh
#
# Uses linux/build.sh's patched tree (SRC/linux-7.2.9, default ~/LITEX-68K/src).
set -e
HERE=$(cd "$(dirname "$0")" && pwd)
TOP=$(cd "$HERE/../../.." && pwd)
SRC=${SRC:-$HOME/LITEX-68K/src}
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
cat "$TOP/linux/litex-rd68031.config" "$HERE/linux-buildroot.config" > "$TMP/fragment"
K="make -s -C $SRC/linux-7.2.9 O=$TMP/build ARCH=m68k CROSS_COMPILE=m68k-linux-gnu-"
KCONFIG_ALLCONFIG="$TMP/fragment" $K allnoconfig
$K savedefconfig
{
	echo "# SPDX-License-Identifier: CERN-OHL-S-2.0"
	echo "# Generated by make-linux-defconfig.sh from linux/litex-rd68031.config"
	echo "# (adapted from RD68031's rd-virt.config) and linux-buildroot.config."
	echo "# Do not edit: change those and regenerate."
	cat "$TMP/build/defconfig"
} > "$HERE/linux.defconfig"
echo "wrote $HERE/linux.defconfig"
